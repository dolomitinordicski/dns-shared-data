import assert from 'node:assert/strict';
import { canTransitionActivation, validateActivationCapacity } from '../dist/partner-activation.js';
const base={applicationId:'app1',status:'started',source:'self-declared',updatedAt:'2026-10-27'};
assert.equal(canTransitionActivation(base,'approved','claimant'),false);
assert.equal(canTransitionActivation(base,'email-verified','system'),false);
assert.equal(canTransitionActivation({...base,emailVerifiedAt:'2026-10-27'},'email-verified','system'),true);
const verified={...base,status:'email-verified',emailVerifiedAt:'2026-10-27'};
assert.equal(canTransitionActivation(verified,'second-factor-verified','system'),false);
assert.equal(canTransitionActivation({...verified,secondFactorVerifiedAt:'2026-10-27'},'second-factor-verified','system'),true);
const pending={...verified,status:'claim-pending',secondFactorVerifiedAt:'2026-10-27',claimantAuthUid:'uid'};
assert.equal(canTransitionActivation(pending,'approved','claimant'),false);
assert.equal(canTransitionActivation(pending,'approved','trusted-reviewer'),false);
const approved={...pending,claimApprovedAt:'2026-10-27',claimApprovedBy:'dns',claimMethod:'dns-review'};
assert.equal(canTransitionActivation(approved,'approved','trusted-reviewer'),true);
assert.equal(canTransitionActivation({...approved,status:'approved'},'active','system'),false);
assert.equal(canTransitionActivation({...approved,status:'approved',establishmentId:'est1'},'active','system'),true);
assert.equal(validateActivationCapacity({...base,authorizedBedCount:-2}),false);
assert.equal(validateActivationCapacity({...base,authorizedBedCount:null}),true);
console.log('Activation contract transition assertions passed');
